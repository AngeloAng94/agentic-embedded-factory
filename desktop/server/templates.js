/**
 * RTOS project templates - shared between web and desktop versions.
 */

const zephyrCMake = (name) => `cmake_minimum_required(VERSION 3.20.0)
find_package(Zephyr REQUIRED HINTS $ENV{ZEPHYR_BASE})
project(${name})

target_sources(app PRIVATE src/main.c)
`;

const zephyrConf = `# Application Kconfig
CONFIG_GPIO=y
CONFIG_SERIAL=y
CONFIG_CONSOLE=y
CONFIG_PRINTK=y

# Stack and thread defaults
CONFIG_MAIN_STACK_SIZE=2048
CONFIG_SYSTEM_WORKQUEUE_STACK_SIZE=2048
`;

const zephyrMain = `#include <zephyr/kernel.h>
#include <zephyr/sys/printk.h>

int main(void)
{
    printk("Zephyr firmware starting on %s\\n", CONFIG_BOARD);

    while (1) {
        printk("tick\\n");
        k_sleep(K_SECONDS(1));
    }

    return 0;
}
`;

const freeRTOSCMake = (name) => `cmake_minimum_required(VERSION 3.20.0)
project(${name} C CXX ASM)

set(CMAKE_C_STANDARD 11)

# FreeRTOS configuration
set(FREERTOS_CFG_DIRECTORY    "\${CMAKE_CURRENT_SOURCE_DIR}/src")
set(FREERTOS_SOURCE_DIRECTORY "\${CMAKE_CURRENT_SOURCE_DIR}/third_party/FreeRTOS-Kernel")

include_directories(
    "\${FREERTOS_CFG_DIRECTORY}"
    "\${FREERTOS_SOURCE_DIRECTORY}/include"
    "\${FREERTOS_SOURCE_DIRECTORY}/portable/GCC/ARM_CM4F"
)

add_executable(\${PROJECT_NAME}
    src/main.c
    \${FREERTOS_SOURCE_DIRECTORY}/tasks.c
    \${FREERTOS_SOURCE_DIRECTORY}/queue.c
    \${FREERTOS_SOURCE_DIRECTORY}/list.c
    \${FREERTOS_SOURCE_DIRECTORY}/timers.c
    \${FREERTOS_SOURCE_DIRECTORY}/portable/MemMang/heap_4.c
    \${FREERTOS_SOURCE_DIRECTORY}/portable/GCC/ARM_CM4F/port.c
)

target_compile_definitions(\${PROJECT_NAME} PRIVATE FREERTOS_CONFIG_H)
`;

const freeRTOSTemplate = `#include "FreeRTOS.h"
#include "task.h"
#include "queue.h"
#include <stdio.h>

static StaticTask_t xTaskBuffer;
static StackType_t xStack[configMINIMAL_STACK_SIZE];
static TaskHandle_t xHandle;

static void vMainTask(void *pvParameters)
{
    (void)pvParameters;
    for (;;) {
        printf("FreeRTOS tick\\n");
        vTaskDelay(pdMS_TO_TICKS(1000));
    }
}

int main(void)
{
    xHandle = xTaskCreateStatic(
        vMainTask,
        "main",
        configMINIMAL_STACK_SIZE,
        NULL,
        tskIDLE_PRIORITY + 1,
        xStack,
        &xTaskBuffer);

    vTaskStartScheduler();

    /* Should never reach here. */
    for (;;) {
    }
}
`;

