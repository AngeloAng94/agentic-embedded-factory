function makeSkeleton(rtos, name) {
  const base = [
    {
      path: "CMakeLists.txt",
      content: rtos === "zephyr" ? zephyrCMake(name) : freeRTOSCMake(name),
      type: "cmake",
    },
    {
      path: "src/main.c",
      content: rtos === "zephyr" ? zephyrMain : freeRTOSTemplate,
      type: "c",
    },
    {
      path: "README.md",
      content: `# ${name}\n\nEmbedded firmware project generated by EmbedFactory.\n\n- RTOS: ${rtos === "zephyr" ? "Zephyr" : "FreeRTOS"}\n- Build: CMake\n\n## Build\n\n${rtos === "zephyr" ? "west build -b <board> -p auto" : "mkdir build && cd build && cmake .. && make"}\n`,
      type: "md",
    },
  ];

  if (rtos === "zephyr") {
    base.push({ path: "prj.conf", content: zephyrConf, type: "conf" });
  } else {
    base.push({ path: "src/FreeRTOSConfig.h", content: freeRTOSConfig, type: "h" });
  }

  return base;
}

